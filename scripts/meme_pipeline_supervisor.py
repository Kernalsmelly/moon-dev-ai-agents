@dataclass
class ProcSpec:
    name: str
    cmd: list[str]
    log_path: Path


def spawn(spec: ProcSpec, env: dict[str, str]) -> subprocess.Popen:
    # Keep a dedicated log file per child process. Close the parent handle
    # immediately after spawn so repeated restarts don't leak descriptors.
    with open(spec.log_path, "a", encoding="utf-8") as log:
        # start_new_session detaches process group so it survives shell exits
        proc = subprocess.Popen(
            spec.cmd,
            stdout=log,
            stderr=subprocess.STDOUT,
            start_new_session=True,
            cwd=str(BASE),
            env=env,
        )
    return proc


def _acquire_singleton_lock() -> bool:
    """Ensure only one supervisor instance runs at a time."""
    global _LOCK_FH
    try:
        LOCK_FILE.parent.mkdir(parents=True, exist_ok=True)
        fh = open(LOCK_FILE, "a+", encoding="utf-8")
        fcntl.flock(fh.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        fh.seek(0)
        fh.truncate()
        fh.write(f"{os.getpid()}\n")
        fh.flush()
        _LOCK_FH = fh  # keep file handle alive for lock lifetime
        return True
    except OSError:
        return False
    except Exception:
        return False

def build_env() -> dict[str, str]:
    """Reload .env and return the environment dict for child processes.

    This makes tuning iteration smoother: updating `.env` and restarting a single
    process is enough; we do not need to restart the whole supervisor.
    """
    # 1) Load primary project env.
    primary_env = BASE / ".env"
    load_dotenv(dotenv_path=str(primary_env), override=True)
    # 2) Optional deterministic runtime env (flattened from `.env`).
    runtime_env_raw = str(os.getenv("MEME_ENV_FILE", "") or "").strip()
    if runtime_env_raw:
        runtime_env = Path(runtime_env_raw)
        if not runtime_env.is_absolute():
            runtime_env = BASE / runtime_env
        if runtime_env.exists():
            load_dotenv(dotenv_path=str(runtime_env), override=True)
    env = os.environ.copy()
    # Default to whatever the user has in .env; only set a fallback if none is present.
    env.setdefault("RPC_URL", env.get("RPC_ENDPOINT", "") or "")
    # If an RPC pool was generated by scripts/key_health_check.py, allow consumers to rotate automatically.
    # Prefer config/rpc_pool.json (gitignored) to avoid accidentally committing provider URLs.
    env.setdefault("RPC_POOL_FILE", str(BASE / "config" / "rpc_pool.json"))
    return env


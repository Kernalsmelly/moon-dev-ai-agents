def _auto_apply_tuning(env: dict[str, str], procs: dict[str, subprocess.Popen]) -> None:
    """Optionally apply next_tuning.json and restart meme_bot.

    Controlled by EDGE_DECIDER_AUTO_APPLY=1 (default off).
    """
    enabled = str(env.get("EDGE_DECIDER_AUTO_APPLY", "")).strip().lower() in ("1", "true", "yes")
    if not enabled:
        return
    if not NEXT_TUNING.exists():
        return
    try:
        obj = json.loads(NEXT_TUNING.read_text(encoding="utf-8"))
    except Exception:
        return
    if not isinstance(obj, dict):
        return
    gen = float(obj.get("generated_at") or 0.0)
    change = obj.get("change") if isinstance(obj.get("change"), dict) else {}
    if not gen or not change:
        return

    # Keep a tiny in-memory guard in procs dict to avoid re-applying the same proposal.
    last_gen = getattr(_auto_apply_tuning, "_last_gen", 0.0)  # type: ignore[attr-defined]
    if gen <= float(last_gen or 0.0):
        return
    setattr(_auto_apply_tuning, "_last_gen", gen)  # type: ignore[attr-defined]

    try:
        with open(AUTO_TUNING_LOG, "a", encoding="utf-8") as fh:
            fh.write(f"{time.time():.0f} apply_next_tuning gen={gen} change_keys={list(change.keys())}\n")
    except Exception:
        pass

    # Apply env updates to .env.
    try:
        subprocess.run(
            [PYTHON, "-u", str(BASE / "scripts" / "apply_next_tuning.py")],
            cwd=str(BASE),
            env=env,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=10,
            check=False,
        )
    except Exception:
        return

    # Restart meme_bot so new env is loaded (build_env reloads .env).
    try:
        proc = procs.get("meme_bot")
        if proc and proc.poll() is None:
            proc.terminate()
    except Exception:
        pass


def _maybe_reap_stale_positions(env: dict[str, str]) -> None:
    """Best-effort hygiene: mark extremely old DB 'open' positions as stale.

    This prevents dashboards/tools from treating week-old crash leftovers as active.
    """
    # Run at most once per hour.
    last = getattr(_maybe_reap_stale_positions, "_last_run", 0.0)  # type: ignore[attr-defined]
    if last and (time.time() - float(last)) < 3600:
        return
    setattr(_maybe_reap_stale_positions, "_last_run", time.time())  # type: ignore[attr-defined]

    hours_raw = str(env.get("MEME_REAP_STALE_OPEN_HOURS") or "").strip()
    # If not configured, still do a conservative reap (24h) because it is safe and
    # helps prevent confusion when iterating quickly.
    if not hours_raw:
        hours_raw = "24"
    try:
        hours = float(hours_raw)
    except Exception:
        return
    if hours <= 0:
        return
    try:
        res = subprocess.run(
            [PYTHON, "-u", str(BASE / "scripts" / "reap_stale_positions.py")],
            cwd=str(BASE),
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            timeout=12,
            check=False,
            text=True,
        )
        out = (res.stdout or "").strip()
        if out:
            with open(REAP_LOG, "a", encoding="utf-8") as fh:
                fh.write(f"{time.time():.0f} {out}\n")
    except Exception:
        return


def main() -> int:
    # Detach from any controlling terminal/process group so this supervisor survives
    # when launched from a short-lived wrapper (e.g. editor tool invocation).
    try:
        os.setsid()
    except Exception:
        pass

    if not _acquire_singleton_lock():
        try:
            with open(LOGS / "meme_pipeline_supervisor.log", "a", encoding="utf-8") as slog:
                slog.write(f"{time.time():.0f} supervisor_exit duplicate_instance\n")
        except Exception:
            pass
        print("meme_pipeline_supervisor: another instance is already running; exiting.")
        return 0

    # Load once at startup for initial settings.
    load_dotenv(dotenv_path=str(BASE / ".env"), override=True)

    supervisor_log = LOGS / "meme_pipeline_supervisor.log"
    env = build_env()

    # Append an auto session log entry so we keep state across long runs.
    try:
        subprocess.run(
            [PYTHON, "-u", str(BASE / "scripts" / "codex_session_log.py")],
            cwd=str(BASE),
            env=env,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=8,
            check=False,
        )
    except Exception:
        pass

    procs: dict[str, subprocess.Popen] = {}

    with open(supervisor_log, "a", encoding="utf-8") as slog:
        slog.write("Supervisor start\n")
        slog.flush()

    while True:
        env = build_env()
        specs = build_specs(env)
        desired_names = {s.name for s in specs}

        # Optional: apply next tuning proposal and restart meme_bot.
        try:
            _maybe_reap_stale_positions(env)
            _auto_apply_tuning(env, procs)
        except Exception:
            pass

        # Stop any processes that are no longer desired (env changed).
        for name, proc in list(procs.items()):
            if name in desired_names:
                continue
            try:
                if proc and proc.poll() is None:
                    proc.terminate()
            except Exception:
                pass
            procs.pop(name, None)

        # spawn missing or dead processes
        for spec in specs:
            proc = procs.get(spec.name)
            if proc is None or proc.poll() is not None:
                with open(supervisor_log, "a", encoding="utf-8") as slog:
                    status = "spawn" if proc is None else f"restart(exit={proc.returncode})"
                    slog.write(f"{time.time():.0f} {spec.name} {status}\n")
                    slog.flush()
                proc = spawn(spec, env=env)
                procs[spec.name] = proc

        time.sleep(5)


if __name__ == "__main__":
    raise SystemExit(main())
